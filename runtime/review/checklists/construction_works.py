def _raw_excerpt(text: str, anchor: re.Pattern[str] | None) -> str:
    """앵커가 걸린 자리의 **계약 원문 그대로**를 잘라 온다.

    조항 추출기가 돌려주는 텍스트는 줄바꿈·공백이 정규화돼 있어 원문과 글자
    단위로 일치하지 않는다. 그대로 인용으로 쓰면 가짜 인용 게이트가 90% 기준에
    걸려 항목을 걷어낸다(광고 체크리스트 실측: 9건 중 8건 탈락).
    """
    body = str(text or "")
    if anchor is None or not body:
        return ABSENT_MARKER
    m = anchor.search(body)
    if m is None:
        return ABSENT_MARKER
    start = body.rfind("\n", 0, m.start()) + 1
    end = body.find("\n", m.end())
    if end == -1:
        end = len(body)
    excerpt = body[start:end].strip()
    return excerpt[:400] if excerpt else ABSENT_MARKER


def _resolve_anchor(
    check: ConstructionCheck, clauses: list[Any] | None,
) -> tuple[dict[str, Any] | None, re.Pattern[str] | None]:
    """이 지적을 붙일 조항과, 그 자리를 찾아낸 패턴을 함께 돌려준다.

    좁은 패턴(`anchor_specific`)이 있으면 먼저 시도한다. 그 패턴이 맞는 조항을
    찾으면 그 조항이 바로 "이 지적이 다루는 법률효과가 규정된 자리" 다. 못
    찾았을 때만 총칭 패턴으로 내려간다 — 총칭으로 먼저 찾으면 "책임" 이라는
    낱말이 처음 나오는 준공검사 조항에 책임전가 지적이 붙는다(실측).
    """
    if check.title_anchor is not None:
        probe = check.anchor_specific or check.anchor
        if probe is not None:
            loc = find_article_for_pattern(
                clauses, probe, title_pattern=check.title_anchor,
            )
            if loc is not None:
                return loc, probe
    if check.anchor_specific is not None:
        loc = find_article_for_pattern(clauses, check.anchor_specific)
        if loc is not None:
            return loc, check.anchor_specific
    if check.anchor is not None:
        return find_article_for_pattern(clauses, check.anchor), check.anchor
    return None, None


def scopes_for(model: ConstructionTransactionModel) -> tuple[str, ...]:
    """이 지위에서 돌려야 할 체크리스트 묶음.

    지위를 확정하지 못했으면 아무것도 돌리지 않는다 — 틀린 방향의 체크리스트를
    주입하는 것이 유형 오분류 주입과 같은 실패다(지시 9항).
    """
    if not model.is_settled:
        return ()
    if model.is_owner_side:
        return (SCOPE_OWNER,)
    scopes = [SCOPE_CONTRACTOR]
    if model.subcontract_relationship_in_scope:
        scopes.append(SCOPE_SUBCONTRACT)
    return tuple(scopes)


#: 이미 나온 finding 이 이 축을 다루고 있는지 볼 때 읽는 필드.
_EXISTING_TEXT_FIELDS = (
    "issue_title", "problem", "rewrite_reason", "legal_business_reason",
    "suggested_rewrite", "recommendation_text",
)


def _already_covered(check: ConstructionCheck, existing: list[dict[str, Any]] | None) -> bool:
    """다른 경로가 이미 같은 축을 **완성 문안까지** 붙여 지적했는가.

    체크리스트는 "이 지위에서 반드시 봐야 할 축" 을 채우는 장치이지, 이미 있는
    지적을 한 번 더 하는 장치가 아니다. 실측: 계약 원문의 지체상금 조항을
    정규식으로 잡아 상한·예외 문안까지 붙인 rule finding 과 CWC-05 가 나란히
    HIGH 로 올라왔다 — 담당자에게는 같은 말이 두 번 보인다.

    판정은 **태그 전부**가 그 finding 의 말 안에 있을 때만 한다(AND). 낱말
    하나로 겹침을 판단하면 정상 항목이 대량으로 사라진다. 그리고 상대 finding 에
    그대로 삽입 가능한 문안이 있을 때만 양보한다 — 문안 없는 지적에 자리를
    내주면 지시 8항(모든 HIGH/MEDIUM 에 완성 조문)이 깨진다.
    """
    if not existing or not check.tags:
        return False
    for cr in existing:
        if not isinstance(cr, dict) or bool(cr.get("is_construction_checklist")):
            continue
        if not str(cr.get("suggested_rewrite") or "").strip():
            continue
        blob = "\n".join(str(cr.get(k) or "") for k in _EXISTING_TEXT_FIELDS)
        if all(tag in blob for tag in check.tags):
            return True
    return False


def run_construction_checklist(
    *,
    text: str,
    clauses: list[Any] | None,
    model: ConstructionTransactionModel,
    existing_results: list[dict[str, Any]] | None = None,
    reserved_articles: set[str] | None = None,
) -> list[dict[str, Any]]:
    """지위에 맞는 체크리스트를 돌려 clause_result 형태로 돌려준다.

    `reserved_articles` 는 이미 다른 경로(유치권·대금 패키지)가 지적을 붙인
    조항이다. 같은 조항에 또 붙이면 한 조항에 대한 수정문안이 여러 개가 되어
    담당자가 무엇을 넣어야 할지 알 수 없다.
    """
    scopes = scopes_for(model)
    if not scopes:
        return []

    body = str(text or "")
    out: list[dict[str, Any]] = []
    #: 이미 지적을 붙인 조항. 같은 조항에 두 번 붙이면 담당자에게는 한 조항에
    #: 대한 두 개의 수정문안이 되고, 어느 것을 넣어야 하는지 알 수 없다
    #: (2026-09-18 지시 10항 — 동일 finding 중복 금지).
    anchored_articles: set[str] = set(reserved_articles or ())
    medium_count = 0
    subcontract_count = 0
    superseded: set[str] = set()
    for c in ALL_CHECKS:
        if c.scope in scopes and c.supersedes:
            superseded.update(c.supersedes)
    # 우선순위 순으로 본다 — 같은 조항에 둘이 걸리면 더 중요한 쪽이 자리를
    # 차지해야 한다. 지시 3항의 축 순서(대금 → 추가공사 → 책임전가 → 공기 →
    # 안전 → 해지 → 보증)가 곧 이 순서다.
    for check in sorted(ALL_CHECKS, key=lambda c: (c.priority, c.check_id)):
        if check.scope not in scopes:
            continue
        if check.check_id in superseded:
            continue
        if check.trigger_when is not None and not check.trigger_when.search(body):
            continue
        if check.satisfied_when is not None and check.satisfied_when.search(body):
            continue
        if _already_covered(check, existing_results):
            continue

        # 절차 보완류(MEDIUM)를 무제한으로 쌓지 않는다. 지시 서두 —
        # "체크리스트식으로 많이 지적하지 말고 실제 금전손실과 책임전가
        # 가능성이 큰 핵심 리스크만 우선 검토." HIGH(실제 금전·책임 리스크)는
        # 제한하지 않는다.
        is_for_subcontract = check.target_contract == "subcontract"
        if is_for_subcontract:
            if subcontract_count >= MAX_SUBCONTRACT_CHECKS:
                continue
        elif check.severity != "HIGH" and medium_count >= MAX_MEDIUM_CHECKS:
            continue

        if is_for_subcontract:
            # [지시 4항] 재하도급 계약에 들어갈 조문을 원도급 계약의 조항에
            # 앵커링하지 않는다. 앵커를 아예 잡지 않고 별도 계약의 신설로 둔다.
            loc, used_anchor = None, None
        else:
            loc, used_anchor = _resolve_anchor(check, clauses)
            if loc is not None:
                article = str(loc.get("article_number") or "")
                if article and article in anchored_articles:
                    continue
        quoted = _raw_excerpt(body, used_anchor) if used_anchor is not None else ABSENT_MARKER
        if not is_for_subcontract:
            edit_location = location_insert_after_last_paragraph(loc)
        marker = paragraph_marker(
            (loc["max_paragraph_number"] + 1) if loc and loc["max_paragraph_number"] else 1
        )
        # 완성 조문은 여러 항으로 이루어져 있다. 첫 항의 번호만 실제 조 구조에
        # 맞추고 나머지는 그대로 둔다 — 번호를 지어내지 않기 위함이다.
        clause_text = check.clause_text
        if marker and marker != "①":
            clause_text = f"[{marker} 이하로 신설]\n{clause_text}"
        if is_for_subcontract:
            display_path = SUBCONTRACT_DOC_LABEL
            edit_location = f"{SUBCONTRACT_DOC_LABEL} — 해당 조항 신설"
        else:
            display_path = f"제{loc['article_number']}조" if loc else "신설 조항"

        redline = build_redline_instruction(
            clause_id=check.check_id,
            severity=check.severity,
            edit_location=edit_location,
            edit_type="insert_after" if loc else "new_clause",
            replacement_text=clause_text,
            reason=check.problem,
        )
        if loc is not None and str(loc.get("article_number") or ""):
            anchored_articles.add(str(loc["article_number"]))
        if is_for_subcontract:
            subcontract_count += 1
        elif check.severity != "HIGH":
            medium_count += 1

        problem = check.problem
        if is_for_subcontract:
            problem = (
                "[이 항목은 지금 검토하는 원도급 계약이 아니라, 우리 회사가 전문업체와 "
                "따로 체결할 재하도급 계약에 반영할 사항입니다.] " + problem
            )
        out.append({
            "clause_id": check.check_id,
            "article_number": (loc["article_number"] if loc else None),
            "display_path": display_path,
            "clause_title": check.issue_title[:60],
            "clause_topic": check.clause_topic,
            "risk_tier": check.severity,
            "severity": check.severity,
            "counsel_severity": check.severity,
            "high_risk": check.severity == "HIGH",
            "must_fix": check.severity == "HIGH",
            "approval_required": check.severity == "HIGH",
            "review_tier": "MUST" if check.severity == "HIGH" else "SUGGEST",
            "high_severity_basis": check.high_basis,
            "issue_title": check.issue_title,
            "original_text": quoted,
            "problem": problem,
            "legal_business_reason": check.legal_business_reason,
            "suggested_rewrite": clause_text,
            "recommendation_text": clause_text,
            "proposed_revision": clause_text,
            "rewrite_reason": problem,
            "negotiation_position": check.negotiation_position,
            "negotiation_strategy": check.negotiation_position,
            "worst_case_scenario": check.worst_case,
            "redline_instruction": redline,
            "confidence": 0.9,
            "is_mandatory": True,
            "is_construction_checklist": True,
            "construction_scope": check.scope,
            "construction_target_contract": check.target_contract,
            "applies_to_separate_subcontract": is_for_subcontract,
            "is_new_clause": bool(is_for_subcontract or loc is None),
            "construction_tags": list(check.tags),
            "detected_issue_list": [{"issue_title": check.issue_title[:120]}],
        })
    return out
