def _rx(p: str) -> re.Pattern[str]:
    return re.compile(p, re.IGNORECASE)


@dataclass
class ConstructionCheck:
    check_id: str
    scope: str
    severity: str                       # HIGH / MEDIUM
    issue_title: str
    problem: str
    legal_business_reason: str
    clause_text: str                    # 그대로 삽입 가능한 완성 조문
    negotiation_position: str
    #: 이 지적을 붙일 조항을 찾는 패턴(총칭). 넓게 잡아도 되는 자리다.
    anchor: re.Pattern[str] | None = None
    #: 그 법률효과를 **제목**에 달고 있는 조항을 찾는 패턴. 있으면 가장 먼저
    #: 본다 — 본문 매치는 문서 순서로 잡히므로, 안전 책임 지적이 계약금액
    #: 조항(본문에 '산업안전보건관리비')에 붙는 일이 실제로 있었다
    #: (2026-09-21 지시 5항 Semantic Anchor).
    title_anchor: re.Pattern[str] | None = None
    #: **그 지적이 다루는 법률효과 자체**를 가리키는 좁은 패턴. 있으면 먼저
    #: 시도한다 — 지체상금 문제를 공정관리 조항에 붙이지 않기 위함이다
    #: (2026-09-18 지시 7항: 문제점 → 수정 위치 → 수정문구가 같은 법률효과).
    anchor_specific: re.Pattern[str] | None = None
    #: 낮을수록 먼저. 같은 조항에 두 지적이 걸리면 이 값이 낮은 쪽만 남긴다.
    priority: int = 50
    #: 이 수정문안이 들어갈 **계약서**. "this" 는 지금 검토하는 계약(원도급),
    #: "subcontract" 는 우리가 전문업체와 따로 체결할 재하도급 계약이다.
    #:
    #: 2026-09-18 지시 4항 — "재하도급 관계에 적용되는 의무를 원도급 계약
    #: 수정문구에 그대로 삽입하지 말 것." 실측: 하도급법 60일 지급기한 문안이
    #: 원도급 계약 제3조(공사대금)에 앵커링됐다. 발주자에게 그 조문을 내밀면
    #: 적용되지 않는 법으로 협상하는 것이 된다.
    target_contract: str = "this"
    #: 이 체크가 나가면 함께 내보내지 않을 다른 체크(같은 이야기를 두 번 하지
    #: 않기 위함 — 지시 10항).
    supersedes: tuple[str, ...] = ()
    #: 이 위험이 계약에 **실제로 존재**한다는 신호. 없으면 지적하지 않는다.
    trigger_when: re.Pattern[str] | None = None
    #: 이미 충분히 규정되어 있다는 신호. 있으면 지적하지 않는다.
    satisfied_when: re.Pattern[str] | None = None
    clause_topic: str = "other"
    high_basis: str = ""
    worst_case: str = ""
    tags: list[str] = field(default_factory=list)


